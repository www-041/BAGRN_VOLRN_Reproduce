from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from src.benchmark_v1_radiometric_r1.roi_gui import launch_roi_annotator  # noqa: E402


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def main() -> int:
    parser = argparse.ArgumentParser(description="Human-only DZ01V radiometric ROI annotation GUI.")
    parser.add_argument("--pair", help="preselected pair ID, e.g. 00_01")
    parser.add_argument("--reviewer", help="your real reviewer identity (never generated by the tool)")
    parser.add_argument("--second-review", action="store_true", help="independent second review of TEST ROIs")
    parser.add_argument("--auto-candidates", type=Path, help="opt into the isolated R1.5 automatic-ROI review workflow")
    parser.add_argument("--multiband-review", action="store_true",
                        help="use schema-v2 multiband review state in its own read/write directory; legacy history stays read-only")
    parser.add_argument("--machine-suggestions", type=Path,
                        help="load a separate R1.5 machine-suggestion GeoJSON as editable drafts (never an approval)")
    parser.add_argument("--check-env", action="store_true", help="check GUI/data dependencies without opening imagery")
    parser.add_argument("--validate-pair", action="store_true", help="validate pair files and metadata without launching the GUI")
    args = parser.parse_args()

    try:
        import tkinter as tk
        import rasterio
    except Exception as exc:
        print(f"R1_GUI_ENVIRONMENT_UNAVAILABLE: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2

    if args.check_env:
        try:
            root = tk.Tk(); root.withdraw(); root.update_idletasks(); root.destroy()
        except Exception as exc:
            print(f"R1_TK_INITIALIZATION_FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
            return 2
        print(f"R1_GUI_ENVIRONMENT_READY rasterio={rasterio.__version__} tkinter={tk.TkVersion}")
        return 0

    if not args.pair or (not args.validate_pair and (not args.reviewer or not args.reviewer.strip())):
        parser.error("--pair and a non-empty real --reviewer are required unless --check-env is used")

    if args.auto_candidates:
        try:
            sys.path.insert(0, str(ROOT / "src"))
            from benchmark_v1_radiometric_r15.gui import launch_auto_roi_reviewer, launch_multiband_roi_reviewer
            from benchmark_v1_radiometric_r15.inputs import load_pair_inputs
            from benchmark_v1_radiometric_r15.machine_suggestions import load_machine_suggestion_map, sha256_file
            from benchmark_v1_radiometric_r15.storage import load_candidate_collection

            pair_inputs = load_pair_inputs(args.pair, ROOT)
            candidate_path = args.auto_candidates if args.auto_candidates.is_absolute() else ROOT / args.auto_candidates
            candidates = load_candidate_collection(candidate_path, args.pair)
            machine_map = None
            if args.machine_suggestions:
                if not args.multiband_review:
                    parser.error("--machine-suggestions requires --multiband-review")
                machine_path = args.machine_suggestions if args.machine_suggestions.is_absolute() else ROOT / args.machine_suggestions
                machine_map = load_machine_suggestion_map(machine_path, expected_pair_id=args.pair)
                candidate_keys = {(args.pair, str(f["properties"]["candidate_id"])) for f in candidates["features"]}
                if set(machine_map) != candidate_keys:
                    raise ValueError("machine suggestions do not exactly match the frozen candidate identities")
                source_sha = sha256_file(candidate_path)
                if any(row.get("_source_candidate_sha256") != source_sha for row in machine_map.values()):
                    raise ValueError("machine suggestion source-candidate SHA256 does not match the current frozen candidate file")
            available_i = {int(k[1:]): v.path for k, v in pair_inputs.scenes[0].bands.items() if v.usable and v.path}
            available_j = {int(k[1:]): v.path for k, v in pair_inputs.scenes[1].bands.items() if v.usable and v.path}
            review_dir = ROOT / "data/output/benchmark_v1_radiometric_r1_5/reviews"
            snapshot = review_dir / f"{args.pair}_review.json"
            events = review_dir / f"{args.pair}_review_events.jsonl"
            if args.validate_pair:
                print(f"R1.5_PAIR_READY pair={args.pair} candidates={len(candidates['features'])} "
                      f"B9_support={pair_inputs.valid_overlap_pixels} bands_i={len(available_i)} bands_j={len(available_j)}")
                return 0
            root = tk.Tk()
            if args.multiband_review:
                multiband_root = ROOT / "data/output/benchmark_v1_radiometric_r1_5/multiband_reviews"
                band_centers = {int(name[1:]): band.wavelength_center_nm
                    for name, band in pair_inputs.scenes[0].bands.items() if band.usable}
                launch_multiband_roi_reviewer(root, args.pair, candidate_path, available_i, available_j,
                    multiband_root, ROOT / "data/output/benchmark_v1_radiometric_r1_5/reviews",
                    args.reviewer, band_centers, second_review=args.second_review,
                    machine_suggestions=machine_map)
            else:
                launch_auto_roi_reviewer(root, args.pair, candidate_path, available_i, available_j,
                                         snapshot, events, args.reviewer, second_review=args.second_review)
            root.mainloop()
        except Exception as exc:
            print(f"R1.5_AUTO_REVIEW_FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
            return 2
        return 0

    if args.multiband_review:
        parser.error("--multiband-review requires --auto-candidates")
    if args.machine_suggestions:
        parser.error("--machine-suggestions requires --auto-candidates and --multiband-review")

    docs = ROOT / "docs/benchmark/v1"
    r1 = docs / "radiometric_r1"
    scene_rows = read_csv(docs / "scene_inventory.csv")
    pair_rows = read_csv(r1 / "radiometric_pair_inventory.csv")
    manifest = read_csv(ROOT / "data/output/final_pipeline/b9_13scene_formal_v2/scene_manifest.csv")
    manifest_by_scene = {row["scene_id"]: row for row in manifest if row.get("band") == "B9"}
    pair = next((row for row in pair_rows if row.get("pair_id") == args.pair), None)
    if pair is None or pair.get("status") == "NO_VALID_OVERLAP":
        print(f"Pair {args.pair!r} is missing or has no effective valid B9 overlap in the frozen inventory.", file=sys.stderr)
        return 2

    candidate_path = r1 / "radiometric_roi_candidates.geojson"
    if not candidate_path.is_file():
        print("R1 ROI candidates are not prepared. Run scripts/benchmark/prepare_radiometric_r1_rois.py first.", file=sys.stderr)
        return 2
    candidates = json.loads(candidate_path.read_text(encoding="utf-8"))
    pair_features = [f for f in candidates.get("features", []) if f.get("properties", {}).get("pair_id") == args.pair]
    if not pair_features:
        print(f"No preselected ROI proposal exists for {args.pair}; this pair is outside the current shortlist.", file=sys.stderr)
        return 2

    scenes_by_id = {}
    for row in scene_rows:
        scenes_by_id[row["product_id"]] = row
        scenes_by_id[row["scene_id"]] = row
    scene_i, scene_j = pair["scene_i"], pair["scene_j"]
    if scene_i not in scenes_by_id or scene_j not in scenes_by_id:
        print(f"Scene metadata missing for pair {args.pair}.", file=sys.stderr)
        return 2
    try:
        manifest_i, manifest_j = manifest_by_scene[scene_i], manifest_by_scene[scene_j]
        path_i, path_j = Path(manifest_i["b9_path"]), Path(manifest_j["b9_path"])
        if not path_i.is_file() or not path_j.is_file():
            raise FileNotFoundError(f"frozen B9 input path missing: {path_i if not path_i.is_file() else path_j}")
        # Header-only reads verify CRS/band availability; pixels are read later as bounded GUI windows.
        with rasterio.open(path_i) as src_i, rasterio.open(path_j) as src_j:
            if src_i.crs is None or src_j.crs is None or src_i.count < 1 or src_j.count < 1:
                raise ValueError("B9 single-band source is missing CRS or raster band 1")
            pair_shape = f"{src_i.width}x{src_i.height}/{src_j.width}x{src_j.height}"
    except Exception as exc:
        print(f"R1_INPUT_VALIDATION_FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2

    if args.validate_pair:
        print(f"R1_PAIR_READY pair={args.pair} scene_i={scene_i} scene_j={scene_j} B9={pair_shape} candidate_ROIs={len(pair_features)}")
        print(f"B9 i: {path_i}\nB9 j: {path_j}")
        return 0

    output_dir = ROOT / "data/output/benchmark_v1_radiometric_r1/roi_reviews"
    output_csv = output_dir / f"{args.pair}_review.csv"
    events_jsonl = output_dir / f"{args.pair}_review_events.jsonl"
    try:
        root = tk.Tk()
        launch_roi_annotator(
            root, args.pair, scene_i, scene_j, {9: path_i}, {9: path_j},
            {"features": pair_features}, output_csv, events_jsonl, args.reviewer,
            second_review=args.second_review,
        )
        root.mainloop()
    except Exception as exc:
        print(f"R1_GUI_START_FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
